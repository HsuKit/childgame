function chineseMatch(serial) {
  const [point, left, answers] = matchSets[(serial - 126) % matchSets.length], order = [2, 0, 3, 1], right = order.map(i => answers[i]), lookup = Object.fromEntries(order.map((x, j) => [x, j]))
  const prefix = serial < 134 ? '阅读方法整理' : '综合阅读实践'
  return { point, content: { stem: `${prefix}：把${point}内容与正确解释连起来`, left, right, matches: left.map((_, i) => [i, lookup[i]]), explanation: `根据${point}的含义和文章阅读方法逐项配对。` } }
}

export function authorGrade4Chinese() {
  const questions = []; let serial = 0
  for (const [type, difficulty, count] of distribution) for (let index = 0; index < count; index += 1) {
    let point = points[serial % points.length], content
    if (type === 'choice') content = chineseChoice(point, serial, serial % 4)
    else if (type === 'fill') { const [p, stem, answer] = fills[serial - 105]; point = p; content = { stem, answer, explanation: `结合四年级语言和阅读知识，填“${answer}”最恰当。` } }
    else { const item = chineseMatch(serial); point = item.point; content = item.content }
    questions.push({ id: `g4-chinese-authored-${String(serial + 1).padStart(3, '0')}`, subject: 'chinese', grade: 4, difficulty, type, knowledgePoint: point, skill: difficulty === 1 ? 'understand' : difficulty === 2 ? 'apply' : 'reason', tags: ['全国通用', difficulty > 1 ? '信息整合' : '阅读理解'], content, reviewStatus: 'reviewed', version: 1 }); serial += 1
  }
  return questions
}
