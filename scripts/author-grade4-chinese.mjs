function choice(stem, correct, wrong, position, explanation) { const options = [...wrong]; options.splice(position, 0, correct); return { stem, options, answer: position, explanation } }

function chineseChoice(point, serial, position) {
  const index = Math.floor(serial / points.length), p = passages[index]
  if (point === '关联词') { const [stem, answer, wrong] = conjunctions[index]; return choice(stem, answer, wrong, position, `前后分句的逻辑关系适合使用“${answer}”。`) }
  if (point === '句段关系') return choice(`阅读：“${p.text}”这段话的句段关系是？`, p.relation, ['按地点远近排列', '各句互不相关', '只写结论不写依据'], position, `段落内容体现了“${p.relation}”。`)
  if (point === '中心意思') return choice(`阅读：“${p.text}”最恰当的中心意思是？`, p.main, ['只介绍天气和时间', '重点描写人物外貌', '说明一种游戏规则'], position, `关键内容都围绕“${p.main}”展开。`)
  if (point === '证据定位') return choice(`阅读：“${p.text}”哪项信息最能支持“${p.main}”？`, p.evidence, ['文中出现了几个标点', '故事发生在某一天', '段落使用了许多常用字'], position, `“${p.evidence}”是直接支持中心意思的具体证据。`)
  if (point === '概括与推断') return choice(`根据短文：“${p.text}”可以合理推断什么？`, p.inference, ['所有问题都能自动解决', '只要等待就一定成功', '文中人物从不需要合作'], position, `结合文中的做法和结果，可以推断“${p.inference}”。`)
  if (point === '叙事文本') return choice(`阅读：“${p.text}”作者怎样把事情写清楚？`, p.narrative, ['只罗列无关词语', '不断重复同一句话', '完全省略人物行动'], position, `短文${p.narrative}。`)
  if (point === '说明性文本') return choice(`阅读：“${p.text}”下列哪项知识能从文中得到？`, p.fact, ['所有事物的特点都相同', '任何结论都不需要证据', '观察和记录没有作用'], position, `短文明确说明或支持了“${p.fact}”。`)
  const [stem, answer, wrong] = poems[index]; return choice(stem, answer, wrong, position, `结合诗句中的关键词和画面，正确理解是“${answer}”。`)
}

